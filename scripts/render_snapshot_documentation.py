"""Render a factual snapshot document without changing strategy or plans."""

from __future__ import annotations

import argparse
import csv
from decimal import Decimal
from pathlib import Path

import yaml


def display(value) -> str:
    if value is None:
        return "未確認"
    if isinstance(value, (int, float, Decimal)):
        return f"{value:,}"
    return str(value).replace("|", "\\|")


def table(headers: list[str], rows: list[list]) -> list[str]:
    return [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
        *("| " + " | ".join(display(v) for v in row) + " |" for row in rows),
        "",
    ]


def render(snapshot: dict, snapshot_ref: str, manifest: dict, root: Path) -> str:
    date = snapshot["snapshot_date"]
    holdings = snapshot["holdings"]
    total = snapshot["total_assets_jpy"]
    lines = [
        f"# {date} 資産スナップショット",
        "",
        "<!-- Generated by scripts/render_snapshot_documentation.py; do not edit directly. -->",
        "",
        f"Money Forwardの表示資産総額は **{total:,}円**。以下はユーザ指定日を基準にした表示値の記録です。"
        "住宅ローン等を控除した純資産ではありません。",
        "",
        f"正規化データ: `{snapshot_ref}`。出典一覧: `{snapshot['source_evidence']['manifest_ref']}`。",
        "",
        "## 記録の基準と出典",
        "",
        snapshot["source_evidence"]["snapshot_date_basis"],
        snapshot["source_evidence"]["valuation_basis"],
        "画面の同期時刻が不明なため、すべての価格が同時刻の市場価格であるとは扱いません。",
        "",
    ]
    lines += table(["出典ID", "保存先", "受領日"], [
        [source["source_id"], source["path"], source["received_on"]]
        for source in manifest["sources"]
    ])
    lines += [
        "画像は直接確認して転記し、CSVは原本の文字コードで読み取りました。"
        "原本は変更せず保存し、manifestに元パスとSHA-256を記録しています。",
        "",
        "## カテゴリ合計は資産総額と一致",
        "",
        f"構成比は各カテゴリ表示額 ÷ Money Forward資産総額{total:,}円。測定日は{date}です。",
        "",
    ]
    lines += table(["カテゴリ", "表示額（円）", "構成比（%）"], [
        [name, value, f"{value / total * 100:.2f}"]
        for name, value in snapshot["category_totals_jpy"].items()
    ])
    for symbol, title in [("LIQUIDITY", "預金・現金の内訳"), ("POINTS_MILES", "ポイントの内訳")]:
        holding = next(h for h in holdings if h["symbol"] == symbol)
        lines += [f"## {title}", "", f"出典: `{holding['source_ref']}`。", ""]
        headers = ["名称", "保有金融機関・サービス", "表示価値（円）"]
        rows = [[row["name"], row["institution"], row["market_value_jpy"]] for row in holding["components"]]
        if symbol == "POINTS_MILES":
            headers += ["ポイント・マイル数", "表示期限"]
            for row, component in zip(rows, holding["components"], strict=True):
                row += [component["quantity"], component.get("expires_on") or "記載なし"]
        lines += table(headers, rows)
        if symbol == "LIQUIDITY":
            lines += ["PayPayの負数も表示どおり含めています。米ドルの円評価額に、CSVの外貨残高を重ねて加算しません。", ""]
        else:
            lines += ["各ポイント・マイルの画面上の換算レートは1.00。Tポイントの期限は基準日より過去ですが、失効・利用可否は未確認です。", ""]
    for category in ["株式（現物）", "投資信託"]:
        lines += [f"## {category}の保有明細", "", "数量・価格・評価額・損益はMoney Forward表示値、口座区分はCSVとの対応です。", ""]
        lines += table(["安定ID", "銘柄名", "金融機関／口座", "数量", "平均取得単価", "現在値", "円評価額", "円評価損益"], [
            [h["symbol"], h["name"], f"{h['institution']}／{h['account_type']}", h["quantity"], h["avg_cost"], h["current_price"], h["market_value_jpy"], h["profit_loss_jpy"]]
            for h in holdings if h["source_category"] == category
        ])
        unit_note = "数量は株、米国株の単価はUSD、国内株の単価は円です。" if category == "株式（現物）" else "数量は口、単価は1万口あたり円です。"
        lines += [unit_note + "特定口座の源泉徴収区分は既存メタデータを継承しています。", ""]
    pension = next(h for h in holdings if h["source_category"] == "年金")
    lines += ["## 年金の表示額", ""]
    lines += table(["銘柄", "取得価額（円）", "現在価値（円）", "評価損益（円）"], [
        [pension["name"], pension["acquisition_cost_jpy"], pension["market_value_jpy"], pension["profit_loss_jpy"]]
    ])
    lines += ["iDeCo区分は既存記録を継承しました。今回画像に金融機関・制度区分・口数・取得日は表示されていません。", "", "## CSVとの差は別の観測値として保持", ""]
    lines += table(["安定ID", "MF数量", "CSV数量", "MF価格", "CSV価格", "MF評価額（円）", "CSV評価額（円）", "差額 CSV−MF（円）"], [
        [h["symbol"], h["quantity"], h["broker_observation"]["quantity"], h["current_price"], h["broker_observation"]["current_price"], h["market_value_jpy"], h["broker_observation"]["market_value_jpy"], h["broker_observation"]["market_value_jpy"] - h["market_value_jpy"]]
        for h in holdings if h.get("broker_observation", {}).get("quantity") is not None
    ])
    lines += [
        "楽天の円預り金はMoney ForwardとCSVで異なります。投資信託の数量差との因果関係は未確認です。"
        "トヨタの現在値は画面の整数表示とCSVの小数表示が異なりますが、数量・評価額・評価損益は一致します。",
        "",
    ]
    # Read vendor summary values directly; do not maintain a second manual copy.
    rakuten = next(source for source in manifest["sources"] if source["source_id"] == "rakuten_csv")
    with (root / rakuten["path"]).open(encoding=rakuten["encoding"], newline="") as stream:
        csv_rows = list(csv.reader(stream))
    detail_header = next(i for i, row in enumerate(csv_rows) if row and row[0] == "種別")
    summary = {row[0]: row[1] for row in csv_rows[:detail_header] if len(row) > 1 and row[0] in {"資産合計", "保有商品の評価額合計", "米国株式", "投資信託", "預り金合計", "預り金", "外貨預り金"}}
    lines += table(["楽天CSVの集計項目", "表示額（円）"], [[name, value] for name, value in summary.items()])
    lines += [
        f"楽天CSVのファイル名が示す出力時刻: {rakuten.get('exported_at_from_filename') or '未確認'}。",
        snapshot["source_evidence"]["broker_export_time_basis"],
        f"参考米ドル円レートは {snapshot['source_evidence']['usd_jpy_reference']['value']} 円/USD"
        f"（表示時刻 {snapshot['source_evidence']['usd_jpy_reference']['displayed_at']}）。"
        "楽天CSVの値であり、Money Forwardへ適用した為替とは断定しません。",
        "",
        "## 検証結果と未確認事項",
        "",
        *(f"- {note}" for note in snapshot["validation_notes"]),
        "",
        "## 既存記録との関係",
        "",
        *(f"- {note}" for note in snapshot["normalization_notes"]),
        "",
        "過去スナップショット、約定・税務記録、承認済み戦略・計画は変更しません。"
        "日付固定の計画は従来の基準スナップショットを参照し続けます。今回の残高差から取引日時や税務値は逆算しません。",
        "",
        "## 再生成方法",
        "",
        "```sh",
        f".venv/bin/python scripts/render_snapshot_documentation.py --snapshot {snapshot_ref} --output reports/snapshots/{date}.md",
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--snapshot", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    snapshot = yaml.safe_load((root / args.snapshot).read_text(encoding="utf-8"))
    manifest = yaml.safe_load((root / snapshot["source_evidence"]["manifest_ref"]).read_text(encoding="utf-8"))
    output = root / args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(snapshot, args.snapshot, manifest, root), encoding="utf-8")


if __name__ == "__main__":
    main()
